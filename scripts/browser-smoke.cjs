// Fixture-only browser validation. Never runs against a live Dex backend.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.HUGIN_PLAYWRIGHT_MODULE || 'playwright-core');
(async () => {
  const base = process.env.HUGIN_WEB_URL || 'http://127.0.0.1:3000';
  const api = process.env.HUGIN_API_URL || 'http://127.0.0.1:8001';
  assert.equal((await (await fetch(`${api}/api/health`)).json()).mode, 'fixture', 'This smoke test requires explicit fixture mode');
  const browser = await chromium.launch({ executablePath: process.env.HUGIN_CHROMIUM || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    const external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (!request.url().startsWith(base) && !request.url().startsWith(api) && /^https?:/.test(request.url())) external.push(request.url()); });
    await page.goto(base);
    await page.getByText('FIXTURE MODE', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: 'Search Dex contacts' }).fill('Jamie Vale');
    await page.getByRole('button', { name: 'Search Dex', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.hg-contact').length === 2);
    assert.equal(await page.getByRole('button', { name: 'Run simulated enrichment' }).count(), 0, 'Ambiguous selection cannot start research');
    await page.getByRole('textbox', { name: 'Search Dex contacts' }).fill('Alex River');
    await page.getByRole('button', { name: 'Search Dex', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.hg-contact').length === 1);
    await page.locator('.hg-contact').click();
    const paidDex = page.getByRole('checkbox').nth(2);
    await paidDex.check();
    assert.equal(await page.getByRole('checkbox').nth(0).isDisabled(), true, 'Paid Dex research cannot be represented as a dry run');
    assert.equal(await page.getByRole('checkbox').nth(1).isChecked(), true, 'Dex auto-fill behavior must be visible');
    await paidDex.uncheck();
    await page.getByRole('button', { name: 'Run simulated enrichment' }).click();
    await page.getByRole('heading', { name: 'Cited research note' }).waitFor({ timeout: 20000 });
    await page.getByText('This was a simulated response.', { exact: false }).waitFor();
    assert.match(await page.locator('.hg-note').innerText(), /https:\/\/example.org\/team\/alex/);
    assert.match(await page.locator('.hg-note').innerText(), /identity high/);
    await page.getByRole('heading', { name: 'Entity snapshot', exact: true }).waitFor();
    const apiJob = await (await fetch(`${api}/api/enrichments/${await page.locator('#hg-run').inputValue()}`)).json();
    assert.ok(apiJob.options.sources.includes('api_anything'));
    assert.equal(apiJob.outcomes.filter(row => row.source.startsWith('api_anything:') && row.outcome === 'ok').length, 3);
    assert.ok(apiJob.evidence.some(row => row.provider === 'api_anything' && row.operation === 'europepmc:search'));
    assert.ok(apiJob.findings.some(row => row.kind === 'publication' && row.status === 'unresolved'));
    await page.getByRole('button', { name: 'Contacts', exact: true }).click();
    await page.getByRole('textbox', { name: 'Search Dex contacts' }).fill('Alex River');
    await page.getByRole('button', { name: 'Search Dex', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.hg-contact').length === 1);
    await page.locator('.hg-contact').click();
    await page.locator('#linkedin-profile-html').setInputFiles(require('node:path').join(__dirname, '../tests/fixtures/linkedin-profile.html'));
    await page.getByText('Attached: linkedin-profile.html', { exact: false }).waitFor();
    await page.getByRole('button', { name: 'Run simulated enrichment' }).click();
    await page.getByRole('heading', { name: 'Cited research note' }).waitFor({ timeout: 20000 });
    const imported = await (await fetch(`${api}/api/enrichments/${await page.locator('#hg-run').inputValue()}`)).json();
    assert.ok(imported.evidence.some(row => row.provider === 'linkedin' && row.evidence_origin === 'user_supplied_html'));
    assert.ok(imported.findings.filter(row => row.provider_review_status === 'pending').some(row => row.kind === 'education'));
    assert.equal(imported.costs.paid_attempts, 0);
    assert.ok(!('linkedin_html' in imported.options), 'Raw HTML is not exposed in job responses');
    assert.match(await page.locator('.hg-note').innerText(), /Example College/);
    const fullJob = await page.locator('#hg-run').inputValue();
    const emptyResponse = await fetch(`${api}/api/enrichments`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ dex_contact_id: 'fixture-alex', sources: ['dex_cached'], idempotency_key: `browser-empty-${Date.now()}` }) });
    assert.equal(emptyResponse.status, 202);
    const emptyJob = (await emptyResponse.json()).job.id;
    await page.getByRole('button', { name: 'Refresh runs', exact: true }).click();
    await page.locator('#hg-run').selectOption(emptyJob);
    await page.getByText('No supported findings. Nothing was saved to Dex.', { exact: false }).first().waitFor();
    assert.equal(await page.getByRole('button', { name: 'Retry sync only' }).count(), 0);
    await page.locator('#hg-run').selectOption(fullJob);
    await page.getByRole('button', { name: 'Evidence', exact: true }).click();
    await page.getByRole('heading', { name: 'Evidence for this run' }).waitFor();
    assert.ok(await page.locator('blockquote').count() > 0);
    await page.getByText('Evidence origin: user supplied html', { exact: false }).first().waitFor();
    await page.getByRole('button', { name: 'Connections', exact: true }).click();
    await page.getByRole('heading', { name: 'Jamie Vale', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Integrations', exact: true }).click();
    await page.getByRole('heading', { name: 'Sources & access' }).waitFor();
    await page.getByRole('heading', { name: 'API Anything', exact: true }).waitFor();
    await page.getByText('OpenAlex author directory', { exact: true }).waitFor();
    assert.ok((await page.locator('.hg-integration-grid').innerText()).includes('fixture'));
    await page.getByRole('button', { name: 'Contacts', exact: true }).click();
    const screenshot = process.env.HUGIN_SCREENSHOT;
    if (screenshot) await page.screenshot({ path: screenshot, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile viewport should not overflow');
    assert.deepEqual(errors, [], 'No browser exceptions');
    assert.deepEqual(external, [], 'Private workspace should not request external analytics or assets');
    console.log('PASS: fixture banner, ambiguous selector, paid-source controls, enrichment, cited note, typed entity snapshot, no-results/no-write UI, sync receipt, evidence, connections, integrations, mobile layout; no external requests or page errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
